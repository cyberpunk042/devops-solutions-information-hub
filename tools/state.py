"""
tools/state.py — Regenerate `.cursor/` common-state surface.

Per operator directive 2026-05-09 turn 8: a gitignored per-system cache of
pre-rendered project state for `/view`, `/questions`, and any other
operator/AI surface to read quickly.

Usage:
    .venv/bin/python -m tools.state regenerate              # all files
    .venv/bin/python -m tools.state regenerate view         # just view-snapshot.md
    .venv/bin/python -m tools.state regenerate questions    # just questions-snapshot.md
    .venv/bin/python -m tools.state regenerate vision       # just vision.md
    .venv/bin/python -m tools.state regenerate focus        # just focus.md
    .venv/bin/python -m tools.state regenerate trace        # just trace.md
    .venv/bin/python -m tools.state status                  # what's stale
    .venv/bin/python -m tools.state show <file>             # cat a snapshot

Source-of-truth: wiki/ + git + raw/notes/ + .assistant/ — the regenerator
just synthesizes these into the .cursor/ render-cache. Loss of .cursor/ is
fully recoverable from sources.
"""

from __future__ import annotations

