from pathlib import Path

PROJECT_ROOT = Path(os.environ.get("CLAUDE_PROJECT_DIR", "/home/jfortin/devops-solutions-information-hub"))
CURSOR_DIR = PROJECT_ROOT / ".cursor"
META_PATH = CURSOR_DIR / "_meta.json"


# ─────────── helpers ────────────


def now_iso() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def git(*args: str) -> str:
    try:
        return subprocess.check_output(["git", "-C", str(PROJECT_ROOT), *args], text=True, stderr=subprocess.STDOUT).strip()
    except subprocess.CalledProcessError as e:
        return f"(git error: {e.output.strip()})"


def hash_inputs(*paths: Path) -> str:
    h = hashlib.sha256()
    for p in paths:
        if p.is_file():
            h.update(p.read_bytes())
        elif p.is_dir():
            for f in sorted(p.rglob("*.md")):
                h.update(f.read_bytes())
    return h.hexdigest()[:16]


def load_meta() -> dict:
    if META_PATH.exists():
        with open(META_PATH) as f:
            return json.load(f)
    return {"schema_version": 1, "files": {}}


def save_meta(meta: dict) -> None:
    CURSOR_DIR.mkdir(parents=True, exist_ok=True)
    with open(META_PATH, "w") as f:
        json.dump(meta, f, indent=2)


def regenerator() -> str:
    """Identifier of the regenerating actor — assistant name or 'operator-manual'."""
    return os.environ.get("ASSISTANT_PROFILE", os.environ.get("USER", "manual"))


