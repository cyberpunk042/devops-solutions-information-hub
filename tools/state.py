    out.append("## 1. PROGRESS — trajectory + trend\n\n")
    log_25 = git("log", "--oneline", "-25")
    out.append("### Recent 25 commits\n\n```\n")
    out.append(log_25 + "\n")
    out.append("```\n\n")
    # Commit cadence
    last_month = git("log", "--since=30.days.ago", "--oneline")
    commits_30d = len([l for l in last_month.splitlines() if l.strip()])
    out.append(f"### Cadence: {commits_30d} commits in the last 30 days\n\n")
    # Recent wiki/log/ entries
    log_dir = PROJECT_ROOT / "wiki" / "log"
    if log_dir.exists():
        recent_logs = sorted(log_dir.glob("2026-*.md"), reverse=True)[:5]
        if recent_logs:
            out.append("### Recent session logs\n\n")
            for p in recent_logs:
                out.append(f"- [`{p.name}`](wiki/log/{p.name})\n")
            out.append("\n")
    out.append("### Trend annotation\n\n")
    out.append("*(Synthesized from commit cadence + recent log titles. `/view` skill may re-synthesize.)*\n\n")
    out.append("---\n\n")

    # ─── 2. POSITION ───
    out.append("## 2. POSITION — current state\n\n")
    branch = git("branch", "--show-current")
    status_short = git("status", "--short")
    last_commit_subj = git("log", "-1", "--pretty=%s")
    last_commit_when = git("log", "-1", "--pretty=%cr")
    ahead_behind = git("status", "--short", "--branch")
    out.append("| Fact | Value |\n|---|---|\n")
    out.append(f"| Branch | `{branch}` |\n")
    out.append(f"| Last commit | {last_commit_subj} |\n")
    out.append(f"| Last commit age | {last_commit_when} |\n")
