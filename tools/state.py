# ─────────── regen entrypoint ────────────

REGENERATORS = {
    "view": ("view-snapshot.md", regen_view),
    "questions": ("questions-snapshot.md", regen_questions),
    "vision": ("vision.md", regen_vision),
    "focus": ("focus.md", regen_focus),
    "trace": ("trace.md", regen_trace),
}


def cmd_regenerate(args: argparse.Namespace) -> int:
    CURSOR_DIR.mkdir(parents=True, exist_ok=True)
    targets = list(REGENERATORS.keys()) if args.target == "all" else [args.target]
    meta = load_meta()
    meta.setdefault("files", {})
    for tgt in targets:
        if tgt not in REGENERATORS:
            print(f"Unknown target: {tgt} (known: {list(REGENERATORS.keys()) + ['all']})", file=sys.stderr)
            return 1
        filename, fn = REGENERATORS[tgt]
        print(f"  regenerating .cursor/{filename}...")
        content = fn()
        (CURSOR_DIR / filename).write_text(content)
        meta["files"][filename] = {
            "last_regenerated": now_iso(),
            "regenerated_by": regenerator(),
            "size_bytes": len(content.encode()),
        }
    meta["last_regenerated"] = now_iso()
    meta["regenerated_by"] = regenerator()
    meta["regeneration_count"] = meta.get("regeneration_count", 0) + 1
    save_meta(meta)
    print(f"  ✓ Done. Meta: {META_PATH}")
    return 0


def cmd_status(args: argparse.Namespace) -> int:
    meta = load_meta()
    print(f"Cursor state at {CURSOR_DIR}")
    print(f"Last regenerated: {meta.get('last_regenerated', '(never)')}")
    print(f"Regenerated by:   {meta.get('regenerated_by', '(n/a)')}")
    print(f"Total regens:     {meta.get('regeneration_count', 0)}")
    print()
    print(f"{'File':<30} {'Last regenerated':<22} {'Size'}")
    print(f"{'-' * 30} {'-' * 22} {'-' * 8}")
    for fname, info in meta.get("files", {}).items():
        print(f"{fname:<30} {info.get('last_regenerated') or '(never)':<22} {info.get('size_bytes', 0)} bytes")
    return 0


def cmd_show(args: argparse.Namespace) -> int:
    p = CURSOR_DIR / args.file
    if not p.exists():
        print(f"Not found: {p}", file=sys.stderr)
        return 1
    print(p.read_text())
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(prog="state", description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)
    sp = sub.add_parser("regenerate", help="Regenerate .cursor/ files")
    sp.add_argument("target", nargs="?", default="all", help="all | view | questions | vision | focus | trace")
    sp.set_defaults(func=cmd_regenerate)
    sp = sub.add_parser("status", help="What's stale in .cursor/")
    sp.set_defaults(func=cmd_status)
    sp = sub.add_parser("show", help="Print a .cursor/ file")
    sp.add_argument("file")
    sp.set_defaults(func=cmd_show)
    args = parser.parse_args()
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
